import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

const provenance = JSON.parse(
  readFileSync(new URL("../vendor/openartifacts/source.json", import.meta.url), "utf8")
);
const source = readFileSync(new URL("../vendor/openartifacts/SKILL.md", import.meta.url), "utf8");
// https://github.com/logancyang/obsidian-copilot/issues/3121: ship immutable local
// instructions so publishing never depends on a CDN or an unpublished npm version.
if (createHash("sha256").update(source).digest("hex") !== provenance.sha256) {
  throw new Error("Vendored OpenArtifacts skill does not match its recorded source hash.");
}
const shared = source
  .match(/^## Shared publishing rules\n([\s\S]*?)^## Standalone CLI\n/m)?.[1]
  .trim();
if (!shared) throw new Error("The vendored OpenArtifacts skill has no shared publishing rules.");
const target = fileURLToPath(
  new URL("../src/agentMode/skills/builtin/openArtifactsSharedRules.ts", import.meta.url)
);
const sourceUrl = `${provenance.repository}/blob/${provenance.commit}/${provenance.path}`;
const generated = await format(
  `// Generated by scripts/sync-openartifacts-skill.mjs.\n// Source: ${sourceUrl}\nexport const OPENARTIFACTS_SHARED_RULES = ${JSON.stringify(shared + "\n")};\n`,
  { ...(await resolveConfig(target)), parser: "typescript" }
);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) {
    throw new Error(
      "Bundled OpenArtifacts rules differ from the vendored source. Run npm run sync:openartifacts-skill."
    );
  }
} else {
  writeFileSync(target, generated);
}
