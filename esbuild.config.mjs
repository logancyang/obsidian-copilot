import esbuild from "esbuild";
import process from "process";
import { createRequire } from "module";
import wasmPlugin from "./wasmPlugin.mjs";
import nodeModuleShim, { nodeBuiltinExternals } from "./nodeModuleShim.mjs";
import svgrPlugin from "./svgrPlugin.mjs";

// CommonJS plugin loaded via createRequire — pure JS, no ESM export needed.
const patchRendererUnsafeUnref = createRequire(import.meta.url)(
  "./scripts/patchRendererUnsafeUnref.js"
);
const { createBundleSizeGuard } = createRequire(import.meta.url)("./scripts/bundleSizeGuard.js");

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
if (typeof import_meta === 'undefined') {
  var import_meta = {
    url: typeof __filename !== 'undefined' ? 'file://' + __filename : 'file:///obsidian-plugin'
  };
}
var process = globalThis.process || {
  env: {},
  platform: '',
  arch: '',
  argv: [],
  version: '',
  versions: {},
  cwd: function () { return '/'; },
  nextTick: function (cb) { Promise.resolve().then(cb); },
  on: function () {},
  off: function () {},
  once: function () {},
  emit: function () { return false; },
};
`;

const prod = process.argv[2] === "production";
const bundleSizeGuard = createBundleSizeGuard({ production: prod });

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  conditions: prod ? ["production"] : ["development"],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...nodeBuiltinExternals,
  ],
  format: "cjs",
  target: "es2020",
  charset: "utf8",
  legalComments: "eof",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [nodeModuleShim, svgrPlugin, wasmPlugin, patchRendererUnsafeUnref, bundleSizeGuard],
  define: {
    global: "window",
    "process.env.NODE_ENV": prod ? '"production"' : '"development"',
    "import.meta.url": "import_meta.url",
  },
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
